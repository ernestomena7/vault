/**
 * Syncs the Vault Design System into the app.
 *
 * The design system in `Vault Design System/` is the source of truth
 * (Constitution VI). This copies its tokens and components into `src/` so Next
 * can import them with clean paths. Nothing here is edited by hand — a design
 * change is made in the design system and re-synced.
 *
 * Run: npm run ds:sync
 */
import { cp, mkdir, readdir, readFile, writeFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DS = path.join(root, 'Vault Design System');
const TOKENS_OUT = path.join(root, 'src', 'styles', 'tokens');
const COMPONENTS_OUT = path.join(root, 'src', 'components', 'ds');

if (!existsSync(DS)) {
  console.error(`Design system not found at: ${DS}`);
  process.exit(1);
}

await rm(TOKENS_OUT, { recursive: true, force: true });
await rm(COMPONENTS_OUT, { recursive: true, force: true });
await mkdir(TOKENS_OUT, { recursive: true });
await mkdir(COMPONENTS_OUT, { recursive: true });

// --- Tokens -----------------------------------------------------------------
await cp(path.join(DS, 'tokens'), TOKENS_OUT, { recursive: true });
const tokenFiles = (await readdir(TOKENS_OUT)).filter((f) => f.endsWith('.css'));

// --- Components -------------------------------------------------------------
// The design system components are React with hooks, so each needs the client
// directive to be usable from Next's server components.
await cp(path.join(DS, 'components'), COMPONENTS_OUT, { recursive: true });

const groups = await readdir(COMPONENTS_OUT, { withFileTypes: true });
const exported = [];

for (const group of groups.filter((g) => g.isDirectory())) {
  const dir = path.join(COMPONENTS_OUT, group.name);
  for (const file of await readdir(dir)) {
    const full = path.join(dir, file);

    // Preview cards and prompt docs belong to the design system, not the app.
    if (file.endsWith('.card.html') || file.endsWith('.prompt.md')) {
      await rm(full);
      continue;
    }

    if (file.endsWith('.jsx')) {
      const source = await readFile(full, 'utf8');
      if (!source.startsWith("'use client'")) {
        await writeFile(full, `'use client';\n${source}`, 'utf8');
      }
      exported.push({ name: path.basename(file, '.jsx'), from: `./${group.name}/${file}` });
    }
  }
}

exported.sort((a, b) => a.name.localeCompare(b.name));

const barrel = `'use client';
/**
 * Design system components. Generated by scripts/sync-design-system.mjs —
 * do not edit. Source: Vault Design System/components/
 *
 * Import UI from here, never build a parallel component (Constitution VI).
 */
${exported.map((c) => `export { ${c.name} } from '${c.from}';`).join('\n')}
`;
await writeFile(path.join(COMPONENTS_OUT, 'index.js'), barrel, 'utf8');

const barrelTypes = `${exported
  .map((c) => `export { ${c.name} } from '${c.from.replace(/\.jsx$/, '.js')}';`)
  .join('\n')}\n`;
await writeFile(path.join(COMPONENTS_OUT, 'index.d.ts'), barrelTypes, 'utf8');

console.log(`Synced ${tokenFiles.length} token files and ${exported.length} components.`);
console.log(exported.map((c) => c.name).join(', '));
